// ---------- Choosing and remembering the language ----------

const STORAGE_KEY = 'noto.uiLang';

function startLanguage() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* storage blocked */
  }
  for (const tag of (typeof navigator !== 'undefined' && navigator.languages) || []) {
    const base = String(tag).toLowerCase().split('-')[0];
    if (STRINGS[base]) return base;
  }
  return 'en';
}

let current = typeof window === 'undefined' ? 'en' : startLanguage();

export function uiLang() {
  return current;
}

export function langInfo(code = current) {
  return LANGS.find((l) => l.code === code);
}

// Changes the language of the whole teacher interface and tells the page to redraw
export function setUiLang(code) {
  if (!STRINGS[code] || code === current) return;
  current = code;
  try {
    localStorage.setItem(STORAGE_KEY, code);
  } catch {
    /* ignore */
  }
  applyStaticText();
  document.dispatchEvent(new CustomEvent('noto:language', { detail: code }));
}

export function hasText(key) {
  return key in STRINGS[current] || key in STRINGS.en;
}

// t('opened', { n: 3, total: 45 }) → "3 of 45 opened" (or the same in the chosen language)
export function t(key, vars = {}) {
  const text = STRINGS[current][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''));
}

// The name of a language, written in the current interface language
export function langName(code) {
  return LANG_NAMES[current][code];
}

// "Whole school" or "Classes 6A, 6B" in the current language.
// (Notices made before this change only have a plain className — show it as it is.)
export function audienceLabel(notice) {
  const audience = notice.audience;
  if (audience?.type === 'school') return t('audienceSchool');
  if (audience?.classes?.length) {
    return t(audience.classes.length > 1 ? 'classMany' : 'classOne', { list: audience.classes.join(', ') });
  }
  return notice.className || '';
}

// Fills every element marked with data-i18n="key" (and placeholders / labels for screen readers)
export function applyStaticText() {
  document.documentElement.lang = langInfo().htmlLang;
  for (const node of document.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll('[data-i18n-placeholder]')) node.placeholder = t(node.dataset.i18nPlaceholder);
  for (const node of document.querySelectorAll('[data-i18n-aria-label]')) node.setAttribute('aria-label', t(node.dataset.i18nAriaLabel));
  for (const node of document.querySelectorAll('[data-i18n-alt]')) node.alt = t(node.dataset.i18nAlt);
  const titleKey = document.documentElement.dataset.titleKey;
  if (titleKey) document.title = `${t(titleKey)} — Noto`;
  const picker = document.getElementById('ui-lang');
  if (picker) picker.value = current;
}

// The language menu in the header
export function setupLanguagePicker() {
  const picker = document.getElementById('ui-lang');
  if (picker) {
    picker.replaceChildren(
      ...LANGS.map((l) => Object.assign(document.createElement('option'), { value: l.code, textContent: l.name, lang: l.htmlLang }))
    );
    picker.addEventListener('change', () => setUiLang(picker.value));
  }
  applyStaticText();
}
